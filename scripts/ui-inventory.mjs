// Lists every button, link, field and label in the app, and says whether a browser test (e2e/) or a source-contract test mentions it.
// Usage: node scripts/ui-inventory.mjs [--md docs/UI_COVERAGE.md] [--fail-under 0.9]
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
const root = process.cwd();
const walk = d => readdirSync(d).flatMap(f => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : /\.(tsx|ts|py|mjs)$/.test(p) ? [p] : []; });
const src = walk(join(root, 'src')).filter(p => /\.tsx$/.test(p) && !p.includes('/tests/'));
const e2eText = walk(join(root, 'e2e')).map(p => readFileSync(p, 'utf8')).join('\n');
const unitText = walk(join(root, 'src/tests')).map(p => readFileSync(p, 'utf8')).join('\n');
const area = f => /\/admin\/|AdminPage/.test(f) ? 'admin' : /\/coach\/|CoachPage|CoachBrief|ClientDetail|NudgeBox|JoinPage|AttentionPanel/.test(f) ? 'coach' : 'customer';
const clean = t => t.replace(/\s+/g, ' ').replace(/&[a-z]+;/g, '').trim();
const items = [];
for (const f of src) {
  const s = readFileSync(f, 'utf8'), rel = relative(root, f);
  const add = (kind, text) => { text = clean(text); if (text.length >= 2 && text.length <= 80 && !/[{}]/.test(text) && /[A-Za-z]/.test(text)) items.push({ area: area(f), file: rel, kind, text }); };
  for (const m of s.matchAll(/<button\b[^>]*>([^<]+)</g)) add('button', m[1]);
  for (const m of s.matchAll(/<(?:Link|a|NavLink)\b[^>]*>([^<{]+)</g)) add('link', m[1]);
  for (const m of s.matchAll(/aria-label="([^"{]+)"/g)) add('label', m[1]);
  for (const m of s.matchAll(/placeholder="([^"{]+)"/g)) add('field', m[1]);
  for (const m of s.matchAll(/<h[12]\b[^>]*>([^<{]+)</g)) add('heading', m[1]);
  for (const m of s.matchAll(/\['([A-Z][A-Za-z ,&'’/.-]{2,40})'/g)) if (/(TABS|SECTIONS|tabs|ORDER|OPTIONS|CHOICES)\s*[:=]/.test(s.slice(Math.max(0, m.index - 200), m.index))) add('tab', m[1]);
}
const seen = new Set(); const uniq = items.filter(i => { const k = i.file + '|' + i.kind + '|' + i.text; if (seen.has(k)) return false; seen.add(k); return true; });
const q = t => t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
for (const i of uniq) { const re = new RegExp(q(i.text), 'i'); i.e2e = re.test(e2eText); i.unit = re.test(unitText); i.covered = i.e2e; }
const by = a => uniq.filter(i => i.area === a);
const rate = a => { const x = by(a); return x.length ? x.filter(i => i.covered).length / x.length : 1; };
const lines = ['# UI coverage: every button, link, field and label', '', 'Generated by `node scripts/ui-inventory.mjs`. "Clicked/seen in a browser test" means the words appear in an e2e spec. Everything else is listed so it can be tested or removed.', ''];
lines.push('| Area | Items | In a browser test | Not yet |', '| --- | --- | --- | --- |');
for (const a of ['customer', 'coach', 'admin']) { const x = by(a); lines.push(`| ${a} | ${x.length} | ${x.filter(i => i.covered).length} | ${x.filter(i => !i.covered).length} |`); }
for (const a of ['customer', 'coach', 'admin']) {
  const miss = by(a).filter(i => !i.covered);
  lines.push('', `## ${a}: not yet in a browser test (${miss.length})`, '', '| File | Kind | Text |', '| --- | --- | --- |', ...miss.map(i => `| ${i.file.replace('src/', '')} | ${i.kind} | ${i.text.replace(/\|/g, '/')} |`));
}
const md = process.argv.indexOf('--md'); if (md > 0) writeFileSync(process.argv[md + 1], lines.join('\n') + '\n');
console.log(lines.slice(4, 8).join('\n')); console.log('total', uniq.length);
const fu = process.argv.indexOf('--fail-under'); if (fu > 0) { const min = Number(process.argv[fu + 1]); for (const a of ['customer', 'coach', 'admin']) if (rate(a) < min) { console.error(`FAIL ${a} coverage ${(rate(a) * 100).toFixed(0)}% < ${min * 100}%`); process.exitCode = 1; } }
